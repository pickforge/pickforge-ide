// Generate src/styles/fonts-data.css with the brand fonts embedded as base64
// data: URIs. WebKitGTK (the Tauri webview) rejects the @font-face *network*
// fetch for these TTFs even though they serve fine and CSP allows them, so it
// falls back to system DejaVu. Inlining removes the fetch entirely — the font
// is guaranteed to load in dev and prod. Re-run with: npm run fonts:data
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");
const fontsDir = join(root, "public", "fonts");

// file -> [family, weight]
const FACES = [
  ["geist-v5-latin-300.ttf", "Geist", 300],
  ["geist-v5-latin-regular.ttf", "Geist", 400],
  ["geist-v5-latin-500.ttf", "Geist", 500],
  ["geist-v5-latin-600.ttf", "Geist", 600],
  ["geist-v5-latin-700.ttf", "Geist", 700],
  ["geist-v5-latin-800.ttf", "Geist", 800],
  ["geist-mono-v5-latin-regular.ttf", "GeistMono", 400],
  ["geist-mono-v5-latin-500.ttf", "GeistMono", 500],
  ["geist-mono-v5-latin-600.ttf", "GeistMono", 600],
  ["geist-mono-v5-latin-700.ttf", "GeistMono", 700],
];

const blocks = FACES.map(([file, family, weight]) => {
  const b64 = readFileSync(join(fontsDir, file)).toString("base64");
  return `@font-face {
  font-family: "${family}";
  font-style: normal;
  font-weight: ${weight};
  font-display: swap;
  src: url("data:font/ttf;base64,${b64}") format("truetype");
}`;
});

const out = `/* GENERATED by scripts/generate-fonts-data.mjs — do not edit by hand.
 * Geist (human voice) + Geist Mono (machine voice), SIL OFL 1.1, embedded as
 * base64 so they load in the WebKitGTK webview (which rejects the network
 * @font-face fetch). Regenerate with: npm run fonts:data */
${blocks.join("\n")}
`;

writeFileSync(join(root, "src", "styles", "fonts-data.css"), out);
console.log(
  `wrote src/styles/fonts-data.css (${FACES.length} faces, ${(out.length / 1024) | 0} KB)`,
);
